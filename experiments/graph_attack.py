DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
EPS = 1e-12


# ---------------------------------------------------------------------------
# Witness-finding accuracy (graph-learned prover)
# ---------------------------------------------------------------------------
@torch.no_grad()
def witness_finding_accuracy(model, layout, *, num, seed, reverse=False,
                             chunk=1 << 12):
    """Fraction of instances where the model's emitted phi solves the instance.

    reverse=False: instance (G0, G1=phi(G0)); target witness phi.
    reverse=True : instance (G1, G0); target witness phi^{-1} (phi'(G1)=G0).

    Instances are drawn from a seed stream disjoint from training/validation
    (SEED_DATA, SEED_DATA+1). For n>=6 the instance space is astronomically
    larger than the training set, so this is genuine held-out generalization;
    for n=4,5 the space is small enough that training saturates it, so these
    numbers measure witness reproduction rather than extrapolation (the
    valid-isomorphism rate remains the fair figure, crediting any witness).
    """
    set_seed(seed)
    n = layout.n
    g = torch.Generator().manual_seed(seed + 90001)
    g0 = rand_graphs(num, n, g)
    phi = torch.rand((num, n), generator=g).argsort(dim=1)
    g1 = apply_perm_to_graph(g0, phi, n)

    if reverse:
        first, second, target = g1, g0, torch.argsort(phi, dim=1)
    else:
        first, second, target = g0, g1, phi

    exact = 0
    iso = 0
    for lo in range(0, num, chunk):
        pref = torch.cat([first[lo:lo + chunk], second[lo:lo + chunk]], dim=1)
        seq = generate_blocks(model, pref, layout, ["phi"], valid=True)
        phi_hat = seq[:, layout["phi"]].cpu()
        tgt = target[lo:lo + chunk]
        exact += (phi_hat == tgt).all(dim=1).sum().item()
        # valid-isomorphism: does phi_hat map the first graph to the second?
        iso += is_isomorphism(phi_hat, first[lo:lo + chunk],
                              second[lo:lo + chunk], n).sum().item()
    return {"exact_match": exact / num, "valid_isomorphism": iso / num,
            "num": num}


# ---------------------------------------------------------------------------
# tau estimation for the two conditionings
# ---------------------------------------------------------------------------
@torch.no_grad()
def tau_true_phi(model, layout, *, k1, k2, seed):
    """Context = [G0|G1|phi]; standard estimate_tau with a GraphContext."""
    gc = GraphContext(layout, seed=seed)
    return estimate_tau(model, layout, k1=k1, k2=k2, seed=seed, context_fn=gc)


@torch.no_grad()
def tau_self_phi(model, layout, *, k1, k2, seed, chunk=1 << 14):
    """Prefix = [G0|G1]; the model regenerates phi then psi.

    Conditioning phi(j)=u is realised by the generating permutation of each
    instance (so G1 encodes it), matching Eq. 5's expectation.
    """
    set_seed(seed)
    n = layout.n
    m = n * (n - 1) // 2
    g = torch.Generator().manual_seed(seed)
    tau_raw = torch.zeros((n, n, n, n))
    tau_log = torch.zeros((n, n, n, n))
    phi_per_batch = max(1, chunk // k2)

    for j in range(n):
        for u in range(n):
            phis = rand_perms_with_constraint(k1, n, j, u, g)     # (K1, n)
            g0 = rand_graphs(k1, n, g)                            # (K1, m)
            g1 = apply_perm_to_graph(g0, phis, n)
            marg = torch.zeros((k1, n, n), device=DEVICE)
            for lo in range(0, k1, phi_per_batch):
                pg0 = g0[lo:lo + phi_per_batch].repeat_interleave(k2, dim=0)
                pg1 = g1[lo:lo + phi_per_batch].repeat_interleave(k2, dim=0)
                pref = torch.cat([pg0, pg1], dim=1)
                seq = generate_blocks(model, pref, layout, ["phi", "psi"],
                                      valid=True)
                psis = seq[:, layout["psi"]]
                P = pg0.shape[0] // k2
                oh = F.one_hot(psis.long(), n).float().view(P, k2, n, n)
                marg[lo:lo + P] = oh.mean(dim=1)
            tau_raw[:, j, :, u] = marg.mean(dim=0).cpu()
            tau_log[:, j, :, u] = marg.clamp_min(EPS).log().mean(dim=0).cpu()
        print(f"  self-phi tau: row j={j} done", flush=True)
    return tau_raw, tau_log


# ---------------------------------------------------------------------------
# Test marginals + extraction
# ---------------------------------------------------------------------------
@torch.no_grad()
def test_marginal_graph(model, g0_bits, phi, layout, *, conditioning, k2,
                        chunk=1 << 14):
    """(n,n) psi-marginal for one graph test instance under either conditioning."""
    n = layout.n
    g0 = g0_bits.unsqueeze(0) if g0_bits.dim() == 1 else g0_bits
    g1 = apply_perm_to_graph(g0, phi.unsqueeze(0), n)
    counts = torch.zeros((n, n), device=DEVICE)
    for lo in range(0, k2, chunk):
        s = min(chunk, k2 - lo)
        rg0 = g0.expand(s, -1).to(DEVICE)
        rg1 = g1.expand(s, -1).to(DEVICE)
        if conditioning == "true-phi":
            rphi = phi.unsqueeze(0).expand(s, -1).to(DEVICE)
            ctx = torch.cat([rg0, rg1, rphi], dim=1)
            psis = sample_psi(model, ctx, layout, valid=True)
        else:  # self-phi
            pref = torch.cat([rg0, rg1], dim=1)
            seq = generate_blocks(model, pref, layout, ["phi", "psi"], valid=True)
            psis = seq[:, layout["psi"]]
        counts += F.one_hot(psis.long(), n).float().sum(dim=0)
    return counts / k2


def run_graph_extraction(model, layout, bank, test_instances, *, conditioning,
                         k2, seed, progress_every=25):
    """test_instances: list of (g0_bits, phi_true). Returns results dict."""
    set_seed(seed)
    n = layout.n
    T = len(test_instances)
    top1 = {m: 0 for m in EXTRACTORS}
    topn = {m: 0 for m in EXTRACTORS}
    union1 = unionn = 0
    for t, (g0, phi) in enumerate(test_instances):
        M = test_marginal_graph(model, g0, phi, layout,
                                conditioning=conditioning, k2=k2)
        scores = recover_scores(bank, M.cpu(), tuple(phi.tolist()), n)
        a1 = an = False
        for m in EXTRACTORS:
            top1[m] += scores[m]["top1"]
            topn[m] += scores[m]["topn"]
            a1 |= scores[m]["top1"]
            an |= scores[m]["topn"]
        union1 += a1
        unionn += an
        if (t + 1) % progress_every == 0 or t == T - 1:
            print(f"    graph-extract [{conditioning}] {t+1}/{T}", flush=True)
    fact = math.factorial
    return {
        "n": n, "num_test": T, "k2": k2, "conditioning": conditioning,
        "random_top1_pct": 100.0 / fact(n),
        "random_topn_pct": 100.0 * n / fact(n),
        "extractors": {
            m: {"top1": top1[m], "topn": topn[m], "total": T,
                "top1_pct": 100.0 * top1[m] / T,
                "topn_pct": 100.0 * topn[m] / T} for m in EXTRACTORS},
        "union": {"top1": union1, "topn": unionn, "total": T,
                  "top1_pct": 100.0 * union1 / T,
                  "topn_pct": 100.0 * unionn / T},
    }


def build_graph_test_set(n, num, seed):
    """list of (g0_bits, phi_true); phi is the isomorphism used to build G1.

    Seed stream disjoint from training (SEED_DATA=0, val SEED_DATA+1) and from
    the witness-finding stream, so the extraction test instances are held-out.
    """
    g = torch.Generator().manual_seed(seed + 70001)
    g0 = rand_graphs(num, n, g)
    phi = torch.rand((num, n), generator=g).argsort(dim=1)
    return [(g0[i], phi[i]) for i in range(num)]
