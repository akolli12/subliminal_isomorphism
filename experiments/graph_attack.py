"""Attacks and diagnostics for graph-conditioned provers (non-abstracted).

Two prover checkpoints are relevant:
  graph-given    phi provided in the input (Table 3 comparison)
  graph-learned  phi generated by the model (the non-abstracted experiment)

Witness-finding accuracy (graph-learned only): feed the graphs and let the
model autoregressively emit the phi block. Forward presents (G0, G1) and asks
for phi with phi(G0)=G1; reverse presents (G1, G0) and asks for phi' with
phi'(G1)=G0. We report exact-match to the generating permutation and the
(weaker) valid-isomorphism rate.

Witness-extraction attack: recover the true witness phi from psi-marginals,
under two conditionings:
  true-phi  : context [G0 | G1 | phi_true], sample psi. Isolates leakage.
  self-phi  : prefix [G0 | G1]; the model generates its own phi, then psi.
              Full self-witnessing pipeline (Assumption 3.2).

tau is estimated consistently with each conditioning (Eq. 5): the conditioning
event phi(j)=u is realised through the generating permutation of each sampled
instance.
"""

